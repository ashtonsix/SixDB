#!/usr/bin/env python3
"""Generate compact maintained bindings from retained qualified selections.

This reproduces the production table, not the experiment that ranked recipes.
provenance.json names the full-consumer jobs behind each selected key width.
"""
import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
TARGET = ROOT / "ikea/include/ikea/hashtable/encoding-profiles.h"


def generate():
    profiles = json.loads((HERE / "selected.json").read_text())["profiles"]
    provenance = json.loads((HERE / "provenance.json").read_text())["profiles"]
    assert len(profiles) == len(provenance)
    seen = set()
    lines = [
        "#pragma once",
        "// Generated by workbench/benchmarks/hashtable/profiles/generate.py.",
        "// Qualified selections and per-width provenance live beside that generator.",
        '#include "kernel.h"',
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "namespace ikea::hashtable::detail::profiles {",
        "struct encoding_profile {",
        "    std::string_view cpu,isa;",
        "    unsigned value_bytes;",
        "    std::array<std::uint8_t,65> encoding;",
        "    std::array<search_kernel,65> kernel;",
        "};",
        "using enum search_kernel;",
        f"inline constexpr std::array<encoding_profile,{len(profiles)}> encoding_profiles{{{{",
    ]
    for row, proof in zip(profiles, provenance):
        identity = tuple(row[k] for k in ("cpu", "isa", "value_bytes"))
        assert identity == tuple(proof[k] for k in ("cpu", "isa", "value_bytes"))
        assert identity not in seen and row["value_bytes"] in (0, 8, 64)
        seen.add(identity)
        assert len(row["widths"]) == len(row["kernels"]) == 65
        for k, width in enumerate(row["widths"]):
            budget = 63 if k <= 30 else 95
            maximum = k if k <= 9 else min(64, budget // (budget // (k + 1)) - 1)
            assert k <= width <= maximum
        covered = [k for job in proof["jobs"] for k in range(job["first"], job["last"] + 1)]
        assert covered == list(range(65))
        lines += [
            f'    {{"{row["cpu"]}","{row["isa"]}",{row["value_bytes"]},',
            "     {" + ",".join(map(str, row["widths"])) + "},",
            "     {" + ",".join(row["kernels"]) + "}},",
        ]
    return "\n".join(lines + ["}};", "} // namespace ikea::hashtable::detail::profiles", ""])


def research_header():
    data=json.loads((ROOT/"workbench/spikes/hashtable/multimap/encoding-profiles.json").read_text())["profiles"]
    lines=['#pragma once','#include <ikea/hashtable/encoding-selection.h>',
        'namespace write_arch::multimap_profiles {',
        'using ikea::hashtable::search_kernel; using enum search_kernel;',
        f'inline constexpr std::array<ikea::hashtable::detail::profiles::encoding_profile,{len(data)}> profiles{{{{']
    for row in data:
        lines += [f'    {{"{row["cpu"]}","{row["isa"]}",{row["value_bytes"]},',
            '     {'+','.join(map(str,row['widths']))+'},',
            '     {'+','.join(row['kernels'])+'}},']
    lines += ['}};',
        'constexpr std::optional<ikea::hashtable::encoding_choice> measured(unsigned k,unsigned v,std::string_view cpu,std::string_view isa) {',
        '    if(k>64)return {};',
        '    if(k<=9)return ikea::hashtable::encoding_choice{k,search_kernel::generic};',
        '    for(const auto& p:profiles)if(p.cpu==cpu&&p.isa==isa&&p.value_bytes==v)return ikea::hashtable::encoding_choice{p.encoding[k],p.kernel[k]};',
        '    return {};', '}', '}', '']
    return '\n'.join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--research", action="store_true", help="also generate the separate multimap research bindings")
    args = parser.parse_args()
    text = generate()
    if args.check:
        assert TARGET.read_text() == text, "encoding profiles need regeneration"
    else:
        TARGET.write_text(text)
    if args.research:
        research=ROOT/"workbench/spikes/hashtable/multimap/measured-profiles.h"
        research_text=research_header()
        if args.check:
            assert research.read_text()==research_text,"research profiles need regeneration"
        else:
            research.write_text(research_text)
