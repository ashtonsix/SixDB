function strandNib(measured, fittedNib, u) {
  const p = pointAtDistance(measured, u), blend = smooth((720 - p[1]) / 35);
  let fitted = blend ? fittedNib(u) : { p, radius: 30 };
  // Internal mask cuts meet at the fork. Average their fitted sections over a
  // short travel distance so that crossing a cut cannot kink the moving cap.
  const soften = smooth((700 - p[1]) / 15) * (1 - smooth((620 - p[1]) / 25));
  if (soften) {
    const weights = [1, 4, 6, 4, 1], samples = weights.map((_, i) => fittedNib(u + (i - 2) * 6 / measured.totalLength));
    const average = get => samples.reduce((sum, sample, i) => sum + weights[i] * get(sample) / 16, 0);
    fitted = {
      p: fitted.p.map((v, j) => v + soften * (average(s => s.p[j]) - v)),
      radius: fitted.radius + soften * (average(s => s.radius) - fitted.radius),
      tangents: fitted.tangents.map((edge, k) => edge.map((v, j) => v + soften * (average(s => s.tangents[k][j]) - v))),
    };
  }
  const centre = p.map((v, axis) => v + (fitted.p[axis] - v) * blend);
  const radius = 30 + (fitted.radius - 30) * blend + 8 * smooth((u - .92) / .08);
  const a = pointAtDistance(measured, u - .00001), b = pointAtDistance(measured, u + .00001);
  const length = Math.hypot(b[0] - a[0], b[1] - a[1]);
  const t = [(b[0] - a[0]) / length, (b[1] - a[1]) / length], n = [-t[1], t[0]];
  const edges = (fitted.tangents ?? [t, t]).map(edge => edge.map((v, j) => t[j] + (v - t[j]) * blend));

  // A circular nib clips against the narrowing root. These two cubic halves
  // follow the local edges, staying flatter until the strands have separated.
  const height = radius * (.55 + .45 * smooth((650 - p[1]) / 65)), k = .55228475;
  const left = centre.map((v, j) => v - n[j] * radius);
  const right = centre.map((v, j) => v + n[j] * radius);
  const top = centre.map((v, j) => v + t[j] * height);
  const cap = [left,
    [...left.map((v, j) => v + edges[0][j] * height * k), ...top.map((v, j) => v - n[j] * radius * k), ...top],
    [...top.map((v, j) => v + n[j] * radius * k), ...right.map((v, j) => v + edges[1][j] * height * k), ...right],
  ];
  // Overlap the trail slightly so antialiasing cannot open a seam at the join.
  const behind = point => point.map((v, j) => fmt(v - t[j] * 2)).join(' ');
  const d = routePath(cap.map(c => c.map(v => +fmt(v)))) + `L${behind(right)}L${behind(left)}Z`;
  return { p: centre, radius, d };
}

const layers = strands.map((strand, i) => {
  const measured = measureRoute(strand.route);
  const fittedNib = outlineNib(boundaries[i], strand.route, 0, { edgeTangents: true });
  const stroke = strokeReveal({ ...strand, width: 118, startRadius: 0, progress: motion.progress,
    nib: u => strandNib(measured, fittedNib, u),
  });
  return { ink: `<path d="${routePath(boundaries[i])}Z"/>`, strokes: [stroke] };
});

// Partial compensation for the measured rate of visible ink growth: soften
// the fork's two surges and start settling before the terminal flares. Applying
// one clock to the base, tips and opacity preserves their established handoff.
const duration = 1.6;
const pacingStations = [
  [0, .975], [.08, 1.056], [.16, .720], [.24, 1.135], [.29, 1.311],
  [.32, 1.037], [.345, .838], [.365, 1.093], [.39, .811], [.43, .844],
  [.48, 1.009], [.54, .976], [.61, 1.168], [.73, 1.262], [.88, 1.245],
  [1.04, 1.129], [1.2, .734], [1.34, .527], [1.46, .374], [1.52, .300], [1.6, 3.728],
].map(([time, speed]) => [time / duration, speed]);
const stronger = speedProfile(pacingStations), gentle = speedProfile(
  pacingStations.map(([time, speed]) => [time, 1 + .7 * (speed - 1)]));
// Keep the stronger opening through the fork, then blend into the gentler
// clock before the terminal flares. Position and speed remain continuous.
const pacing = timingCurve(t => {
  const a = stronger.progress(t), b = gentle.progress(t);
  return a + (b - a) * smooth((t * duration - .55) / .5);
});
const timeline = {
  at: time => duration * pacing.progress(time / duration),
  inverse: time => duration * pacing.timeAtDistance(time / duration),
};
const timedLayers = [{ ink, strokes: [base] }, ...layers].map(layer => ({
  ...layer, strokes: layer.strokes.map(stroke => retimeStroke(stroke, timeline)),
}));
const fadeDuration = timeline.inverse(.22);

export const mark = {
  id: 'consurgent', title: 'Consurgent', viewBox: [0, 0, 541, 741],
  description: 'Three softly flared strands rise together from a smooth shared base, finishing in gently flattened caps.',
  ink: () => ink,
  revealAppear: { duration: fadeDuration, scale: 1,
    progress: p => smooth(timeline.at(p * fadeDuration) / .22) },
  revealLayers: () => timedLayers,
};
