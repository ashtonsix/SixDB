#!/usr/bin/env python3
"""Actor-observed proposal timing; no change to eligibility or existing positions."""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import hashlib
import json
from pathlib import Path

from experiments import run_writes


class Timing:
    """Per-producer payload-receipt watchdog, cooldown, optional window/warnings.

    Has no access to fault declarations, remote durable sets, prefix state,
    consumer success, or another producer's observations.
    """
    def __init__(self, sim, net, config):
        self.sim, self.net, self.config = sim, net, config
        self.pending = defaultdict(dict)
        self.strict_until = defaultdict(float)
        self.events = []
        self.count = Counter()
        self.producers = ([n for n in net.nodes if "_p" in n]
                          if config.get("producers", 1) > 1 else
                          [f"p{s}" for s in range(config.get("shards", 1))])
        # External warning is an explicitly authored independent input, not
        # generated by reading the simulator's fault state. False warnings tested.
        for warning in config.get("warnings", []):
            def send(warning=warning):
                for producer in self.producers:
                    net.send("l0", producer, 32,
                        lambda producer=producer: self.alarm(producer, "received_warning"), "control")
            sim.at(warning, send)

    def alarm(self, producer, reason):
        self.strict_until[producer] = max(self.strict_until[producer],
                                         self.sim.now + self.config.get("cooldown_us", 500))
        self.count[reason] += 1
        if len(self.events) < 40:
            self.events.append(dict(at_us=self.sim.now, producer=producer, reason=reason,
                                    strict_until_us=self.strict_until[producer],
                                    pending_receipts=len(self.pending[producer])))

    def begin(self, producer, key):
        # A window limits unanswered payload receipts, not time that an already
        # allocated journal position may block the global prefix.
        if len(self.pending[producer]) >= self.config.get("sample_limit", 128):
            self.count["strict"] += 1
            self.count["watch_sample_refused"] += 1
            return False
        early = (self.sim.now >= self.strict_until[producer] and
                 all(self.sim.now - born <= self.config.get("observe_after_us", 300)
                     for born in self.pending[producer].values()) and
                 len(self.pending[producer]) < self.config.get("early_window", 1000000))
        self.pending[producer][key] = self.sim.now
        self.count["early" if early else "strict"] += 1
        def timeout():
            if key in self.pending[producer]:
                self.alarm(producer, "missing_payload_receipt")
        self.sim.later(self.config.get("observe_after_us", 300), timeout)
        return early

    def receipt(self, producer, key):
        began = self.pending[producer].pop(key, None)
        if began is not None:
            self.count["observed_first_receipts"] += 1
            # Cooldown expiry alone cannot infer recovery. The next operation
            # also requires no overdue unanswered sample.
            if self.sim.now - began > self.config.get("observe_after_us", 300):
                self.alarm(producer, "observed_slow_receipt")

    def report(self):
        return dict(counters=dict(self.count), events=self.events,
                    pending_receipts={p: len(q) for p, q in self.pending.items()},
                    sample_limit_per_producer=self.config.get("sample_limit", 128),
                    policy="per-producer local timeout and actually received durable-payload replies")


def run(config):
    policy = config.get("timing_policy", "adaptive")
    config = dict(config, admission=("strict" if policy == "strict" else "pipelined_candidate"))
    if policy == "adaptive":
        factory = lambda sim, net: Timing(sim, net, config)
    elif policy in ("strict", "early"):
        factory = None
    else:
        raise ValueError("unknown timing policy")
    return run_writes(config, factory)


def campaign(count=300):
    base = dict(count=count, rate=100000, producers=2, drain_us=10000)
    incidents = {
        "healthy": {},
        "sudden_payload_partition": dict(faults=[dict(kind="partition", src="p0_p0", dst=w,
                                            at_us=300, until_us=1000) for w in ("f0", "s0")]),
        "flapping_payload_path": dict(faults=[dict(kind="partition", src="p0_p0", dst=w,
                                    at_us=t, until_us=t+200) for w in ("f0", "s0") for t in (300, 900, 1500)]),
        "device_slow": dict(faults=[dict(kind="disk_slow", node="f0", factor=20, at_us=300, until_us=1000)]),
        "false_warning": dict(warnings=[100, 700, 1300]),
        "expired_warning": dict(warnings=[100], faults=[dict(kind="partition", src="p0_p0", dst=w,
                                         at_us=600, until_us=1300) for w in ("f0", "s0")]),
        "advance_warning": dict(warnings=[400], faults=[dict(kind="partition", src="p0_p0", dst=w,
                                         at_us=600, until_us=1300) for w in ("f0", "s0")]),
        "sensitive_false_alarms": dict(observe_after_us=150),
    }
    rows = []
    for incident, extra in incidents.items():
        for policy in ("strict", "early", "adaptive"):
            rows.append(dict(base, **extra, name=f"{incident}-{policy}", timing_policy=policy))
    for window in (1, 4):
        rows.append(dict(base, **incidents["sudden_payload_partition"], early_window=window,
                         name=f"sudden_payload_partition-window-{window}", timing_policy="adaptive"))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--count", type=int, default=300)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    root = Path(__file__).parent
    def hashes():
        return {n: hashlib.sha256((root/n).read_bytes()).hexdigest()
                for n in ("proposal_study.py", "experiments.py", "simulator.py", "routing.py")}
    sources = hashes()
    results = [run(c) for c in campaign(args.count)]
    if sources != hashes():
        raise RuntimeError("source changed during study")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(dict(sources=sources, results=results), indent=2)+"\n")
    print(f"{len(results)} proposal-timing comparisons -> {args.output}")


if __name__ == "__main__":
    main()
