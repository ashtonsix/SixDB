#!/usr/bin/env python3
"""Render throughput tables from the audited summaries; selection uses bytes only."""
import argparse
import csv
import json
from pathlib import Path

p = argparse.ArgumentParser()
p.add_argument('root', type=Path, help='Main sweep native/ directory')
p.add_argument('--writes', type=Path, help='Paired follow-up native/ directory')
p.add_argument('--output', type=Path, required=True)
a = p.parse_args()
rows = list(csv.DictReader((a.root / 'summary.csv').open()))
memory = list(csv.DictReader((a.root / 'memory.csv').open()))
plans = json.loads((a.root / 'plan.json').read_text())
schedule = json.loads((a.root / 'schedule.json').read_text())
index = {(r['case'], int(r['v']), r['arm'], r['phase'], int(r['miss']), int(r['prefetch'])): r for r in rows}
memindex = {(r['case'], int(r['v']), r['arm']): r for r in memory}
selected = {}
for plan in plans:
    case, v = plan['name'], plan['v']
    options = [r for r in memory if r['case'] == case and int(r['v']) == v
               and r['arm'].startswith('ikea') and float(r['initial_over_ceiling']) <= 1]
    owner = max(options, key=lambda r: float(r['initial_bytes_median']))
    selected[(case, v)] = [owner['arm'], 'boost_native', 'abseil_budget']

def label(case, v):
    return f"{case.replace('_', ' ').replace('w', 'W')} {'set' if v == 0 else 'map8'}"

def cell(values):
    return ' / '.join(f'{float(x):.1f}' for x in values)

out = ['# Memory-matched Zen 5 scorecard', '',
       'Generated by `memory-report.py`; medians across three seeds. Throughput is',
       '**million operations/s, higher is better**. Read triples mean **all hit /',
       '50% miss / all miss**. Write triples mean **build / 50%-new upsert /',
       'erase+refill pair**. A pair counts one erase and one insertion. Upsert',
       'excludes its separately measured prerequisite half-erasure; the paired',
       'follow-up CSV also includes their combined cost. Build includes allocation.', '',
       '## Actual memory', '',
       'Hot sizes are KiB; cold sizes are MiB. Each cell is **initial / largest',
       'retained / peak simultaneous** allocation plus owner. Selection gives Ikea',
       'its largest tested geometry below the common ceiling, without consulting',
       'timings. It does not grant extra padding or a different logical population.', '',
       '| Fixture | Ikea | Boost | Abseil | Ikea b / encoded width |',
       '| --- | ---: | ---: | ---: | ---: |']
for plan in plans:
    case, v = plan['name'], plan['v']
    rr = [memindex[(case, v, arm)] for arm in selected[(case, v)]]
    unit = 1024**2 if case.startswith('cold') else 1024
    cells = [' / '.join(f"{float(r[k])/unit:.2f}" for k in
              ['initial_bytes_median', 'max_retained', 'max_peak']) for r in rr]
    sample = next(r['file'] for r in schedule if r['case'] == case and
                  r['v'] == v and r['arm'] == selected[(case, v)][0])
    raw = next(csv.DictReader((a.root / 'samples' / sample).open()))
    out.append(f"| {label(case,v)} | {' | '.join(cells)} | {rr[0]['b']} / {raw['e']} |")

def reads(title, phase, cold_prefetch):
    out.extend(['', f'## {title}', '', '| Fixture | Ikea | Boost | Abseil |',
                '| --- | ---: | ---: | ---: |'])
    for plan in plans:
        case, v = plan['name'], plan['v']
        pf = 32 if case.startswith('cold') and cold_prefetch else 0
        cells = []
        for arm in selected[(case,v)]:
            distance = 0 if arm.startswith('boost') else pf
            cells.append(cell(index[(case,v,arm,phase,m,distance)]['mops'] for m in [0,50,100]))
        out.append(f"| {label(case,v)} | {' | '.join(cells)} |")

reads('Independent reads: hot direct; cold home-prefetched', 'read', True)
out.extend(['', 'Cold Ikea/Abseil use their existing home-prefetch API at distance 32.',
            'Boost uses its native candidate prefetch; it exposes no public home hint.',
            'The following direct results keep this scheduling difference visible.'])
reads('Independent reads: all direct', 'read', False)
reads('Independent reads after the common churn: hot direct; cold home-prefetched',
      'read_after_churn', True)
out.extend(['', '## Plain writes, no caller prefetch', '',
            '| Fixture | Ikea | Boost | Abseil |', '| --- | ---: | ---: | ---: |'])
for plan in plans:
    case,v = plan['name'],plan['v']
    cells = [cell(index[(case,v,arm,phase,0,0)]['mops'] for phase in
             ['build','upsert50','erase_refill_pair']) for arm in selected[(case,v)]]
    out.append(f"| {label(case,v)} | {' | '.join(cells)} |")
out.extend(['', '## Map replacement, no caller prefetch', '',
            'Cells mean **ordinary upsert of existing keys / known-existing update**.',
            'Peer known-existing updates use `find` then a direct mapped write.',
            'Set replacements are membership/duplicate operations, not payload writes.', '',
            '| Fixture | Ikea | Boost | Abseil |', '| --- | ---: | ---: | ---: |'])
for plan in plans:
    case,v=plan['name'],plan['v']
    if not v: continue
    cells=[cell(index[(case,v,arm,phase,0,0)]['mops'] for phase in
                ['replace_mixed','replace_existing']) for arm in selected[(case,v)]]
    out.append(f"| {label(case,v)} | {' | '.join(cells)} |")

if a.writes:
    wr=list(csv.DictReader((a.writes/'summary.csv').open()))
    wi={(int(r['w']),int(r['v']),r['impl'],int(r['prefetch']),r['phase']):r for r in wr}
    out.extend(['', '## Paired cold writes with existing home-prefetch APIs', '',
        'A separate paired build compares distance 0 and 32 in the same batch-loop',
        'driver. Disabling the initial read sweep also changes the RNG position used',
        'to shuffle write ranks. Absolute values need not match the earlier sweep;',
        'all five arms run identical work within this cohort.',
        'Cells again mean **build / 50%-new upsert / erase+refill pair**, M/s.', '',
        '| Fixture | Ikea direct | Ikea PF32 | Boost native | Abseil direct | Abseil PF32 |',
        '| --- | ---: | ---: | ---: | ---: | ---: |'])
    for w in [40,50]:
        for v in [0,8]:
            cells=[cell(wi[(w,v,impl,pf,phase)]['mops'] for phase in
                   ['build','upsert50','erase_refill_pair']) for impl,pf in
                   [('ikea',0),('ikea',32),('boost',0),('abseil',0),('abseil',32)]]
            out.append(f"| cold W{w} {'set' if not v else 'map8'} | {' | '.join(cells)} |")
    out.extend(['', 'Map replacement cells mean **ordinary upsert / known-existing**, M/s.', '',
        '| Fixture | Ikea direct | Ikea PF32 | Boost native | Abseil direct | Abseil PF32 |',
        '| --- | ---: | ---: | ---: | ---: | ---: |'])
    for w in [40,50]:
        cells=[cell(wi[(w,8,impl,pf,phase)]['mops'] for phase in
               ['replace_mixed','replace_existing']) for impl,pf in
               [('ikea',0),('ikea',32),('boost',0),('abseil',0),('abseil',32)]]
        out.append(f"| cold W{w} map8 | {' | '.join(cells)} |")
    out.extend(['', 'Complete 50%-new upsert trace, **including its prerequisite half-erasure**, M/s.',
        'One unit is one upsert plus half an erase, at constant live population.', '',
        '| Fixture | Ikea direct | Ikea PF32 | Boost native | Abseil direct | Abseil PF32 |',
        '| --- | ---: | ---: | ---: | ---: | ---: |'])
    for w in [40,50]:
        for v in [0,8]:
            cells=[cell([wi[(w,v,impl,pf,'upsert50_with_erase')]['mops']]) for impl,pf in
                   [('ikea',0),('ikea',32),('boost',0),('abseil',0),('abseil',32)]]
            out.append(f"| cold W{w} {'set' if not v else 'map8'} | {' | '.join(cells)} |")

out.extend(['', '## Capacity frontier, including native and over-budget references', '',
    'All arms remain visible below. Initial bytes may exceed the common ceiling',
    'on explicitly retained upper references; these are excluded from matched wins.',
    'Read triples use direct hot / prefetched cold as above. Writes are build /',
    'upsert / erase+refill pair, unprefetched. Exact bytes, spill, loads, peaks,',
    'all read modes and median absolute deviations are in the CSVs.', '',
    '| Fixture | Arm | Initial KiB or MiB | Ceiling ratio | Reads M/s | Writes M/s |',
    '| --- | --- | ---: | ---: | ---: | ---: |'])
for plan in plans:
    case,v=plan['name'],plan['v']
    for armrec in plan['arms']:
        arm=armrec['name']
        r=memindex[(case,v,arm)]
        pf=32 if case.startswith('cold') and not arm.startswith('boost') else 0
        read=cell(index[(case,v,arm,'read',m,pf)]['mops'] for m in [0,50,100])
        write=cell(index[(case,v,arm,phase,0,0)]['mops'] for phase in
                   ['build','upsert50','erase_refill_pair'])
        unit=1024**2 if case.startswith('cold') else 1024
        out.append(f"| {label(case,v)} | {arm} | {float(r['initial_bytes_median'])/unit:.2f} | "
                   f"{float(r['initial_over_ceiling']):.3f} | {read} | {write} |")
a.output.write_text('\n'.join(out)+'\n')
print(a.output)
